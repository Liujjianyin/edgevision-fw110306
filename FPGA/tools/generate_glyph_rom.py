#!/usr/bin/env python
"""Generate a 32x32 CJK/ASCII glyph ROM for the board-side demo OSD."""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


LABELS = ['乌苏啤酒 8元', '小可口可乐 2.5元', '小青柠 5元', '百事可乐 3元', '背景', '未识别']
GLYPHS = list(dict.fromkeys("".join(LABELS)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/msyh.ttc"))
    args = parser.parse_args()
    if not args.font.is_file():
        raise SystemExit(f"Chinese font not found: {args.font}")
    glyphs = GLYPHS
    if len(set(glyphs)) != len(glyphs) or set(glyphs) != set("".join(LABELS)):
        raise SystemExit("The fixed glyph order must contain every label glyph exactly once")
    if len(glyphs) > 32:
        raise SystemExit(f"Expected <=32 glyphs, got {len(glyphs)}")
    font = ImageFont.truetype(str(args.font), 30)
    rtl_dir = args.project_root / "src" / "rtl" / "proc"
    if not rtl_dir.is_dir():
        rtl_dir = args.project_root / "rtl"
    output = rtl_dir / "drink_font_rom.v"
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "`timescale 1ns/1ps",
        "// Generated by scripts/generate_glyph_rom.py from Microsoft YaHei.",
        "module drink_font_rom(input wire [4:0] glyph_id,input wire [4:0] row,output reg [31:0] bits);",
        "always @* begin",
        " bits=32'd0;",
        " case(glyph_id)",
    ]
    for index, char in enumerate(glyphs):
        canvas = Image.new("L", (32, 32), 0)
        draw = ImageDraw.Draw(canvas)
        draw.text((0, -4), char, font=font, fill=255, stroke_width=0)
        rows = []
        pix = canvas.load()
        for y in range(32):
            value = 0
            for x in range(32):
                if pix[x, y] >= 96:
                    value |= 1 << (31 - x)
            rows.append(value)
        lines.extend([f"  5'd{index}: case(row)"])
        for row, value in enumerate(rows):
            if value:
                lines.append(f"    5'd{row}: bits=32'h{value:08X};")
        lines.extend(["    default: bits=32'd0;", "   endcase"])
    lines.extend(["  default: bits=32'd0;", " endcase", "end", "endmodule", ""])
    lines.extend(
        [
            "module drink_label_rom(input wire [2:0] class_id,input wire [3:0] char_index,output reg [3:0] label_len,output reg [4:0] glyph_id);",
            "always @* begin",
            " label_len=0;glyph_id=0;",
            " case(class_id)",
        ]
    )
    for class_id, label in enumerate(LABELS):
        lines.append(f"  3'd{class_id}: begin label_len=4'd{len(label)}; case(char_index)")
        for char_index, char in enumerate(label):
            lines.append(f"    4'd{char_index}:glyph_id=5'd{glyphs.index(char)};")
        lines.append("    default:glyph_id=0;endcase end")
    lines.extend(["  default:begin label_len=4'd3;case(char_index)"])
    for char_index, char in enumerate(LABELS[-1]):
        lines.append(f"    4'd{char_index}:glyph_id=5'd{glyphs.index(char)};")
    lines.extend(["    default:glyph_id=0;endcase end", " endcase", "end", "endmodule", ""])
    output.write_text("\n".join(lines), encoding="ascii")
    (args.project_root / "glyph_map.json").write_text(
        __import__("json").dumps(
            {"glyph_ids": {char: index for index, char in enumerate(glyphs)}, "labels": LABELS},
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"Generated {len(glyphs)} glyphs: {output}")


if __name__ == "__main__":
    main()
